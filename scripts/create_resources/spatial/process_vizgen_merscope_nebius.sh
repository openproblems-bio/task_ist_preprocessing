# committed and rebuilt onto build/main (this launch uses --revision build/main --pull-latest):
#   - read_boundary_hdf5 no longer hardcodes zIndex_3 (falls back to any available z-plane,
#     logs n_skipped) so it no longer drops/KeyErrors on cells absent at z=3;
#   - the >65535-cell chunked rasterization merges correctly (was silently a no-op before).
# NOTE 2 (auth): inputs are staged from s3://openproblems-data/resources/raw_data/txSim_custom/
# vizgen_merscope (the same bucket the Nebius env reads for every other spatial dataset), NOT
# directly from gs://vz-ffpe-showcase. The showcase bucket is Vizgen's access-controlled GCS
# bucket (an anonymous GET returns "Anonymous caller does not have storage.objects.get access"),
# and the Nebius compute env has no Google Cloud credentials, so staging gs:// paths failed as an
# anonymous caller before the loader ever ran. A z3-only (2D, lossless-for-this-pipeline) copy is
# mirrored to S3 by scripts/create_resources/spatial/upload_vizgen_merscope_2d.sh — run that once
# (from a machine authenticated to both clouds) before launching this.

# get the root of the directory
